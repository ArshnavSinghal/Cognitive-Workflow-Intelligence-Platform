        "Extensions such as the 2-PL model introduce an item discrimination parameter alpha_j, while the 3-PL model introduces a pseudo-guessing "
        "asymptote gamma_j. While IRT is invaluable for adaptive testing (CAT) where the objective is to estimate a unidimensional scalar ability "
        "efficiently, it fails to capture multidimensional cognitive structures. A learner with high overall ability may still exhibit acute "
