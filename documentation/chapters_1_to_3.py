        "   i_t = sigma( W_i * [h_{t-1}, x_t] + b_i )    (Input Gate)\n"
        "   c_tilde_t = tanh( W_c * [h_{t-1}, x_t] + b_c ) (Candidate State)\n"
        "   c_t = f_t * c_{t-1} + i_t * c_tilde_t       (Updated Cell State)\n"
        "   o_t = sigma( W_o * [h_{t-1}, x_t] + b_o )    (Output Gate)\n"
        "   h_t = o_t * tanh(c_t)                       (Hidden State Vector)\n\n"
        "The predicted probability of correctly answering question k at time t+1 is then computed via a linear projection followed by a sigmoid:\n"
        "   y_t = sigma( W_{out} * h_t + b_{out} )"
