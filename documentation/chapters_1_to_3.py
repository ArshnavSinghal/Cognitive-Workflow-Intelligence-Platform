    builder.add_heading_1("3.3 Mathematical Formulation of the Feature Engineering Pipeline")
    builder.add_body_paragraph(
        "Raw activity logs are transformed into a dense, multidimensional representation through an automated 10-feature engineering pipeline. "
        "Each feature is mathematically formulated to isolate a specific dimension of learner capability, velocity, or error structure:"
    )
    builder.add_body_paragraph(
        "1. Skill Accuracy (SA): The baseline empirical accuracy of learner l on skill s across all N historical activities:\n"
        "   SA(l, s) = (1 / N) * Σ_{i=1}^N (score_i / 100.0)\n"
        "where score_i in [0, 100]. When N = 0 (unassessed skill), SA defaults to 0.0 with an unassessed metadata flag."
    )
    builder.add_body_paragraph(
        "2. Weighted Recent Accuracy (WRA): An exponentially decayed accuracy metric that prioritizes recent attempts to capture learning velocity:\n"
        "   WRA(l, s) = ( Σ_{i=1}^N exp(-λ * (t_now - t_i)) * (score_i / 100.0) ) / ( Σ_{i=1}^N exp(-λ * (t_now - t_i)) )\n"
        "where λ is the temporal decay rate (configured at λ = 0.10 day^-1, corresponding to a half-life of approximately 6.93 days). "
        "This formulation guarantees that recent conceptual breakthroughs are not masked by early historical failures."
    )
    builder.add_body_paragraph(
        "3. Difficulty-Stratified Accuracy (DSA): A stratified accuracy vector evaluated across distinct difficulty tiers d in {1, 2, 3, 4, 5}:\n"
        "   DSA(l, s, d) = ( Σ_{i in A(l,s,d)} score_i ) / ( 100.0 * |A(l,s,d)| )\n"
        "where A(l, s, d) denotes the set of activities completed by learner l on skill s at difficulty level d. If a tier has not yet been attempted, "
        "its entry is imputed using isotonic nearest-neighbor interpolation."
    )
    builder.add_body_paragraph(
        "4. First-Attempt Accuracy Ratio (FAR): The ratio of accuracy achieved on initial submissions relative to overall accuracy:\n"
        "   FAR(l, s) = Accuracy_first_attempt(l, s) / ( SA(l, s) + ε )\n"
        "where ε = 1e-6 prevents zero division. Values of FAR significantly below 1.0 flag excessive reliance on trial-and-error guessing rather than conceptual mastery."
    )
    builder.add_body_paragraph(
        "5. Progressive Accuracy Slope (PAS): The ordinary least squares (OLS) linear regression slope of percentage score over chronological time:\n"
        "   PAS(l, s) = ( Σ_{i=1}^N (t_i - t_mean) * (score_i - score_mean) ) / ( Σ_{i=1}^N (t_i - t_mean)^2 )\n"
        "A positive slope reflects steady progression; a zero or negative slope diagnoses cognitive stagnation or regression."
    )
    builder.add_body_paragraph(
        "6. Average Response Time by Difficulty (ARTD): Mean duration normalized against difficulty tier d:\n"
        "   ARTD(l, s, d) = (1 / |A(l,s,d)|) * Σ_{i in A(l,s,d)} duration_i\n"
        "Abnormally high values on low-difficulty tasks diagnose hesitation and poor procedural automaticity."
    )
    builder.add_body_paragraph(
        "7. Retry Rate (RR): The proportion of activities requiring repeated attempts before achieving a passing threshold:\n"
        "   RR(l, s) = |{ i in A(l, s) : attempt_number_i > 1 }| / |A(l, s)|"
    )
    builder.add_body_paragraph(
        "8. Error Consistency Score (ECS): Quantifies whether student errors follow a systematic, reproducible pattern:\n"
        "   ECS(l, s) = 1.0 - ( H(E) / log2(|M|) )\n"
        "where H(E) is the Shannon entropy of observed error distributions across misconception categories M. An ECS near 1.0 indicates "
        "a severe, persistent misconception that requires conceptual review rather than mechanical practice."
    )
    builder.add_body_paragraph(
        "9. Confidence Decay Index (CDI): The regression trajectory of self-reported confidence relative to objective correctness over time, "
        "capturing metacognitive calibration."
    )
    builder.add_body_paragraph(
        "10. Time Pressure Indicator (TPI): The proportion of responses completed under rapid latency thresholds with high error rates, "
        "isolating impulsive guessing behaviors."
    )

