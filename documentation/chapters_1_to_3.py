    builder.add_body_paragraph(
        "When a learner requests a recommendation for a target skill t in which they exhibit an empirical mastery deficit, CWIP does not "
        "naively prescribe target-skill drills. Instead, it activates the diagnose_prerequisites() algorithm. The algorithm inspects every "
        "prerequisite p in Ancestors(t) and computes a comprehensive Bottleneck Severity Score B(p):"
    )
    builder.add_body_paragraph(
        "   B(p) = (1.0 - Mastery_p) * Weight(p, t) * (1.0 + 0.3 * OutDegree(p)) * DepthFactor(p) * PenaltyFactor(p)\n\n"
        "where:\n"
        "• (1.0 - Mastery_p) represents the absolute prerequisite mastery deficit;\n"
        "• Weight(p, t) is the edge dependency strength along the path to the target;\n"
        "• OutDegree(p) scales the score by structural centrality: nodes that serve as prerequisites to multiple downstream skills are prioritized;\n"
        "• DepthFactor(p) = 1.0 / (1.0 + 0.2 * ShortestPathLength(p, t)) prioritizes proximal prerequisites over distant ancestors;\n"
        "• PenaltyFactor(p) = 0.5 if any prerequisite of p itself has Mastery < 0.60, penalizing intermediate nodes when a deeper root cause exists."
    )
